package com.trybe.common.domain;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * 统一错误码枚举 — 三位三段式编码体系
 *
 * <pre>
 * 分段规则：
 *   1xx = 客户端参数错误（参数为空、格式非法、校验不通过）
 *   2xx = 预留禁用（避免与成功码200混淆）
 *   3xx = 身份认证与会话（未登录、Token过期/无效、账号异常）
 *   4xx = 业务逻辑错误（权限不足、数据不存在、重复提交、状态不合法）
 *   5xx = 服务端系统异常（数据库错误、第三方调用失败、未知运行时异常）
 *
 * 强制兼容：
 *   SUCCESS = 200  适配 R.success() 判定逻辑
 *   SERVER_ERROR = 500  适配 R.error(String) 默认值
 *   所有枚举值可作为 CommonException 构造参数，无侵入替换硬编码数字
 * </pre>
 *
 * @author TryBe Team
 */
@Getter
@AllArgsConstructor
public enum ErrorCodeEnum {

    // ======================== 成功 ========================
    /** 操作成功 */
    SUCCESS(200, "操作成功"),

    // ======================== 1xx 客户端参数错误 ========================
    /** 通用参数校验失败 */
    PARAM_ERROR(100, "参数校验失败"),
    /** 必填参数不能为空 */
    PARAM_EMPTY(101, "必填参数不能为空"),
    /** 参数格式不正确 */
    PARAM_FORMAT_ERR(102, "参数格式不正确"),
    /** 参数长度超出限制 */
    PARAM_LENGTH_LIMIT(103, "参数长度超出限制"),
    /** 请求JSON格式错误 */
    JSON_PARSE_ERR(104, "请求JSON格式错误"),

    // ======================== 2xx 预留禁用 ========================
    // 200 = SUCCESS 固定成功码，2xx 其余值禁止使用

    // ======================== 3xx 身份认证与会话 ========================
    /** 通用认证失败 */
    AUTH_FAILED(300, "认证失败"),
    /** 未登录 */
    NOT_LOGIN(301, "未登录，请重新登录"),
    /** 登录凭证已过期 */
    TOKEN_EXPIRE(302, "登录凭证已过期"),
    /** 非法登录凭证 */
    TOKEN_INVALID(303, "非法登录凭证"),
    /** 账号已被冻结 */
    ACCOUNT_FROZEN(304, "账号异常，请联系客服"),

    // ======================== 4xx 业务逻辑错误 ========================
    /** 通用业务逻辑错误 */
    BIZ_ERROR(400, "业务处理失败"),
    /** 权限不足 */
    FORBIDDEN(401, "权限不足"),
    /** 数据不存在 */
    DATA_NOT_FOUND(402, "数据不存在"),
    /** 请勿重复提交 */
    DUPLICATE_SUBMIT(403, "请勿重复提交"),
    /** 业务状态不允许当前操作 */
    STATUS_ERROR(404, "当前状态不支持此操作"),

    // ======================== 5xx 服务端系统异常 ========================
    /** 服务器繁忙 */
    SERVER_ERROR(500, "服务器繁忙，请稍后重试"),
    /** 数据库操作异常 */
    DB_ERROR(501, "数据库操作异常"),
    /** 第三方服务调用失败 */
    THIRD_PARTY_ERROR(502, "第三方服务调用失败");

    /** 错误码 */
    private final int code;
    /** 错误信息 */
    private final String msg;
}
